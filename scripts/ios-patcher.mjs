/**
 * @param {string} section
 * @param {string} inner
 * @returns {string}
 */
function markedBlock(section, inner) {
  return `/* ${BLOCK_BEGIN} [${section}] */\n${inner}\n/* ${BLOCK_END} [${section}] */`
}

/**
 * Replace an existing marked block or insert it before the section end.
 * @param {string} text
 * @param {string} section
 * @param {string} inner
 * @returns {TextEdit}
 */
export function upsertMarkedBlock(text, section, inner) {
  const begin = `/* ${BLOCK_BEGIN} [${section}] */`
  const end = `/* ${BLOCK_END} [${section}] */`
  const pattern = new RegExp(`${escapeRegExp(begin)}[\\s\\S]*?${escapeRegExp(end)}`)
  const block = markedBlock(section, inner)
  if (pattern.test(text)) {
    const next = text.replace(pattern, () => block)
    return { text: next, changed: next !== text }
  }
  const anchor = `/* End ${section} section */`
  if (!text.includes(anchor)) {
    throw new Error(
      `ios-patcher: project.pbxproj is missing "${anchor}"; regenerate ios/ via "cap add ios".`,
    )
  }
  return { text: text.replace(anchor, () => `${block}\n${anchor}`), changed: true }
}

/**
 * @returns {{ files: Record<string, string>, builds: Record<string, string>, product: string, entitlements: string, infoPlist: string, sourcesPhase: string, target: string, configList: string, configDebug: string, configRelease: string }}
 */
function widgetIds() {
  const id = (kind, name) => stableId(`BudgetLensWidget:${kind}:${name}`)
  const files = Object.fromEntries(WIDGET_SOURCES.map((name) => [name, id("file", name)]))
  const builds = Object.fromEntries(WIDGET_SOURCES.map((name) => [name, id("build", name)]))
  return {
    files,
    builds,
    product: id("product", "appex"),
    entitlements: id("file", "entitlements"),
    infoPlist: id("file", "info-plist"),
    sourcesPhase: id("phase", "sources"),
    target: id("target", "widget"),
    configList: id("config", "list"),
    configDebug: id("config", "debug"),
    configRelease: id("config", "release"),
  }
}

/**
 * Apply the widget target registration to project.pbxproj text. All inserted
 * ids are deterministic (see {@link stableId}), so re-running is stable.
 * @param {string} text
 * @param {{ appId: string }} context
 * @returns {PbxprojEdit}
 */
export function applyPbxprojEdits(text, context) {
  const notes = []
  let changed = false
  let next = text
  const ids = widgetIds()
  const t = (value) => `\t\t${value}`

  const track = (section, inner) => {
    const result = upsertMarkedBlock(next, section, inner)
    next = result.text
    if (result.changed) {
      changed = true
      notes.push(section)
    }
  }

  track(
    "PBXFileReference",
    [
      ...WIDGET_SOURCES.map((name) =>
        t(
          `${ids.files[name]} /* ${name} */ = {isa = PBXFileReference; lastKnownFileType = sourcecode.swift; path = ${name}; sourceTree = "<group>"; };`,
        ),
      ),
      t(
        `${ids.infoPlist} /* ${WIDGET_INFO_PLIST} */ = {isa = PBXFileReference; lastKnownFileType = text.plist.xml; path = ${WIDGET_INFO_PLIST}; sourceTree = "<group>"; };`,
      ),
      t(
        `${ids.entitlements} /* ${WIDGET_ENTITLEMENTS} */ = {isa = PBXFileReference; lastKnownFileType = text.plist.entitlements; path = ${WIDGET_ENTITLEMENTS}; sourceTree = "<group>"; };`,
      ),
      t(
        `${ids.product} /* ${WIDGET_TARGET_NAME}.appex */ = {isa = PBXFileReference; explicitFileType = "wrapper.app-extension"; includeInIndex = 0; path = ${WIDGET_TARGET_NAME}.appex; sourceTree = BUILT_PRODUCTS_DIR; };`,
      ),
    ].join("\n"),
  )

  track(
    "PBXBuildFile",
    WIDGET_SOURCES.map((name) =>
      t(
        `${ids.builds[name]} /* ${name} in Sources */ = {isa = PBXBuildFile; fileRef = ${ids.files[name]} /* ${name} */; };`,
      ),
    ).join("\n"),
  )

  track(
    "PBXSourcesBuildPhase",
    [
      t(`${ids.sourcesPhase} /* Sources */ = {`),
      t(`\tisa = PBXSourcesBuildPhase;`),
      t(`\tbuildActionMask = 2147483647;`),
      t(`\tfiles = (`),
      ...WIDGET_SOURCES.map((name) => t(`\t\t${ids.builds[name]} /* ${name} in Sources */,`)),
      t(`\t);`),
      t(`\trunOnlyForDeploymentPostprocessing = 0;`),
      t(`};`),
    ].join("\n"),
  )

  track(
    "PBXNativeTarget",
    [
      t(`${ids.target} /* ${WIDGET_TARGET_NAME} */ = {`),
      t(`\tisa = PBXNativeTarget;`),
      t(
        `\tbuildConfigurationList = ${ids.configList} /* Build configuration list for PBXNativeTarget "${WIDGET_TARGET_NAME}" */;`,
      ),
      t(`\tbuildPhases = (`),
      t(`\t\t${ids.sourcesPhase} /* Sources */,`),
      t(`\t);`),
      t(`\tbuildRules = (`),
      t(`\t);`),
      t(`\tdependencies = (`),
      t(`\t);`),
      t(`\tname = ${WIDGET_TARGET_NAME};`),
      t(`\tproductName = ${WIDGET_TARGET_NAME};`),
      t(`\tproductReference = ${ids.product} /* ${WIDGET_TARGET_NAME}.appex */;`),
      t(`\tproductType = "com.apple.product-type.app-extension";`),
      t(`};`),
    ].join("\n"),
  )

  const buildSettings = (name) => {
    const lines = [
      t(`\t\t\t\tAPPLICATION_EXTENSION_API_ONLY = YES;`),
      t(`\t\t\t\tCODE_SIGN_ENTITLEMENTS = "${WIDGET_TARGET_NAME}/${WIDGET_ENTITLEMENTS}";`),
      t(`\t\t\t\tCODE_SIGN_STYLE = Automatic;`),
      t(`\t\t\t\tCURRENT_PROJECT_VERSION = 1;`),
      t(`\t\t\t\tINFOPLIST_FILE = "${WIDGET_TARGET_NAME}/${WIDGET_INFO_PLIST}";`),
      t(`\t\t\t\tIPHONEOS_DEPLOYMENT_TARGET = ${IOS_DEPLOYMENT_TARGET};`),
      t(`\t\t\t\tMARKETING_VERSION = 1.0;`),
      t(`\t\t\t\tPRODUCT_BUNDLE_IDENTIFIER = "${context.appId}.widget";`),
      t(`\t\t\t\tPRODUCT_NAME = "$(TARGET_NAME)";`),
      t(`\t\t\t\tSKIP_INSTALL = YES;`),
      t(`\t\t\t\tSWIFT_VERSION = 5.9;`),
    ]
    if (name === "Debug") lines.push(t(`\t\t\t\tSWIFT_OPTIMIZATION_LEVEL = "-Onone";`))
    return lines.join("\n")
  }

  const configEntry = (id, name) =>
    [
      t(`${id} /* ${name} */ = {`),
      t(`\tisa = XCBuildConfiguration;`),
      t(`\tbuildSettings = {`),
      buildSettings(name),
      t(`\t};`),
      t(`\tname = ${name};`),
      t(`};`),
    ].join("\n")

  track(
    "XCBuildConfiguration",
    `${configEntry(ids.configDebug, "Debug")}\n${configEntry(ids.configRelease, "Release")}`,
  )

  track(
    "XCConfigurationList",
    [
      t(
        `${ids.configList} /* Build configuration list for PBXNativeTarget "${WIDGET_TARGET_NAME}" */ = {`,
      ),
      t(`\tisa = XCConfigurationList;`),
      t(`\tbuildConfigurations = (`),
      t(`\t\t${ids.configDebug} /* Debug */,`),
      t(`\t\t${ids.configRelease} /* Release */,`),
      t(`\t);`),
      t(`\tdefaultConfigurationIsVisible = 0;`),
      t(`\tdefaultConfigurationName = Release;`),
      t(`};`),
    ].join("\n"),
  )

  if (!next.includes(TARGET_MARKER)) {
    const pattern = /(targets = \(\n[\s\S]*?)(\n[ \t]*\);)/
    if (!pattern.test(next)) {
      throw new Error('ios-patcher: project.pbxproj has no "targets = (...)" array to extend.')
    }
    const line = `\n\t\t\t\t${ids.target} /* ${WIDGET_TARGET_NAME} */, // ${TARGET_MARKER}`
    next = next.replace(pattern, (_match, head, tail) => `${head}${line}${tail}`)
    changed = true
    notes.push("PBXProject-targets")
  }

  return { text: next, changed, notes }
}

/**
 * Minimal line diff for --dry-run output.
 * @param {string} before
 * @param {string} after
 * @returns {DiffLine[]}
 */
export function diffLines(before, after) {
  const a = before.split("\n")
  const b = after.split("\n")
  const rows = Array.from({ length: a.length + 1 }, () => new Array(b.length + 1).fill(0))
  for (let i = a.length - 1; i >= 0; i -= 1) {
    for (let j = b.length - 1; j >= 0; j -= 1) {
      const same = a[i] === b[j] ? 1 : 0
      const diag =
        rows[i + 1] !== undefined && rows[i + 1][j + 1] !== undefined ? rows[i + 1][j + 1] : 0
      const down = rows[i + 1] !== undefined && rows[i + 1][j] !== undefined ? rows[i + 1][j] : 0
      const right = rows[i] !== undefined && rows[i][j + 1] !== undefined ? rows[i][j + 1] : 0
      rows[i][j] = same === 1 ? diag + 1 : Math.max(down, right)
    }
  }
  const get = (i, j) => (rows[i] !== undefined && rows[i][j] !== undefined ? rows[i][j] : 0)
  /** @type {DiffLine[]} */
  const out = []
  let i = 0
  let j = 0
  while (i < a.length && j < b.length) {
    if (a[i] === b[j]) {
      out.push({ type: " ", text: a[i] === undefined ? "" : a[i] })
      i += 1
      j += 1
    } else if (get(i + 1, j) >= get(i, j + 1)) {
      out.push({ type: "-", text: a[i] === undefined ? "" : a[i] })
      i += 1
    } else {
      out.push({ type: "+", text: b[j] === undefined ? "" : b[j] })
      j += 1
    }
  }
  while (i < a.length) {
    out.push({ type: "-", text: a[i] === undefined ? "" : a[i] })
    i += 1
  }
  while (j < b.length) {
    out.push({ type: "+", text: b[j] === undefined ? "" : b[j] })
    j += 1
  }
  return out
}

