/**
 * Deterministic 24-hex Xcode-style id derived from a stable name.
 * @param {string} name
 * @returns {string}
 */
export function stableId(name) {
  return createHash("sha256").update(name, "utf8").digest("hex").slice(0, 24).toUpperCase()
}

/**
 * @param {string} value
 * @returns {string}
 */
export function escapeXml(value) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
}

/**
 * @param {string} value
 * @returns {string}
 */
function escapeRegExp(value) {
  return value.replaceAll(/[$()*+.?[\\\]^{|}]/g, "\\$&")
}

/**
 * Index of the `</dict>` closing the top-level `<dict>` of an XML plist.
 * @param {string} plistXml
 * @returns {number}
 */
export function topLevelDictCloseIndex(plistXml) {
  const plistOpen = plistXml.indexOf("<plist")
  if (plistOpen === -1) throw new Error("ios-patcher: not a plist document (missing <plist>).")
  const firstDict = plistXml.indexOf("<dict", plistOpen)
  if (firstDict === -1) throw new Error("ios-patcher: plist has no top-level <dict>.")
  const token = /<\/?dict(?=[\s>])/g
  token.lastIndex = firstDict
  let depth = 0
  let match = token.exec(plistXml)
  while (match) {
    depth += match[0].startsWith("</") ? -1 : 1
    if (depth === 0) return match.index
    match = token.exec(plistXml)
  }
  throw new Error("ios-patcher: unbalanced <dict> tags in plist.")
}

/**
 * Ensure a top-level `<key>` exists in an XML plist. Existing values are
 * preserved untouched; missing keys are inserted before the top-level close.
 * @param {string} plistXml
 * @param {string} key
 * @param {string} valueXml
 * @returns {TextEdit}
 */
export function ensureTopLevelDictKey(plistXml, key, valueXml) {
  if (plistXml.includes(`<key>${key}</key>`)) return { text: plistXml, changed: false }
  const close = topLevelDictCloseIndex(plistXml)
  const indentMatch = /\n([ \t]*)$/.exec(plistXml.slice(0, close))
  const indent = indentMatch && indentMatch[1] !== undefined ? indentMatch[1] : "\t"
  const entry = `\n${indent}<key>${key}</key>\n${indent}${valueXml}`
  return { text: `${plistXml.slice(0, close)}${entry}\n${plistXml.slice(close)}`, changed: true }
}

/**
 * @param {string} groupId
 * @returns {string}
 */
function freshEntitlements(groupId) {
  return [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">`,
    `<plist version="1.0">`,
    `<dict>`,
    `\t<key>${APP_GROUP_ENTITLEMENT_KEY}</key>`,
    `\t<array><string>${escapeXml(groupId)}</string></array>`,
    `</dict>`,
    `</plist>`,
    ``,
  ].join("\n")
}

/**
 * Ensure the App Group entitlement array contains `groupId`. Creates a fresh
 * entitlements document when none exists; preserves all unrelated keys.
 * @param {string | null} existingXml
 * @param {string} groupId
 * @returns {TextEdit}
 */
export function ensureAppGroupEntitlements(existingXml, groupId) {
  if (existingXml === null) return { text: freshEntitlements(groupId), changed: true }
  if (!existingXml.trimStart().startsWith("<?xml")) {
    throw new Error("ios-patcher: entitlements file is not an XML plist; refusing to edit.")
  }
  const keyTag = `<key>${APP_GROUP_ENTITLEMENT_KEY}</key>`
  if (!existingXml.includes(keyTag)) {
    return ensureTopLevelDictKey(
      existingXml,
      APP_GROUP_ENTITLEMENT_KEY,
      `<array><string>${escapeXml(groupId)}</string></array>`,
    )
  }
  const afterKey = existingXml.indexOf(keyTag) + keyTag.length
  const arrayOpen = existingXml.indexOf("<array", afterKey)
  const headTag = /^\s*<([A-Za-z]+)[\s>]/.exec(existingXml.slice(afterKey))
  if (arrayOpen === -1 || !headTag || headTag[1] !== "array") {
    throw new Error(
      `ios-patcher: ${APP_GROUP_ENTITLEMENT_KEY} exists but is not an <array>; fix it by hand.`,
    )
  }
  const arrayClose = existingXml.indexOf("</array>", arrayOpen)
  if (arrayClose === -1) throw new Error("ios-patcher: unbalanced <array> in entitlements.")
  const inner = existingXml.slice(arrayOpen, arrayClose)
  const needle = new RegExp(`<string>\\s*${escapeRegExp(groupId)}\\s*</string>`)
  if (needle.test(inner)) return { text: existingXml, changed: false }
  return {
    text: `${existingXml.slice(0, arrayClose)}<string>${escapeXml(groupId)}</string>${existingXml.slice(arrayClose)}`,
    changed: true,
  }
}

