#!/usr/bin/env node
// Idempotent patcher for the generated (gitignored) Capacitor ios/ project.
//
// Applies the native capabilities the WidgetKit widget + Siri intent need,
// without hand-editing Xcode files:
//
// 1. App Group entitlement (`com.apple.security.application-groups`) merged
//    into the host app entitlements AND a widget-extension entitlements file.
// 2. Widget target registration: committed Swift sources copied under
//    ios/App/BudgetLensWidget/ (with the App Group id stamped in) plus
//    marker-delimited, deterministically-generated project.pbxproj blocks
//    (file refs, build files, sources phase, appex target, build configs).
// 3. Info.plist keys: NSFaceIDUsageDescription ensured on the host app plist
//    (preserved when already set) and a generated widget extension plist.
//
// Idempotence: every edit is marker-guarded or content-compared, so re-running
// after `cap sync` is a byte-identical no-op. Verify without Xcode via
// `--dry-run` (prints per-file diffs, writes nothing) and `--check` (exit 1
// when drift is detected, for CI). Pure transforms are exported for unit
// tests; there are zero runtime dependencies (node: builtins only).
//
// Plain JavaScript on purpose (JSDoc types, no TS syntax): the file must run
// under any supported node AND import cleanly into vitest/rolldown.
//
// Deferred to the device-validation pass: `xcodebuild -list` / device build
// of the registered appex target, App Group container read/write on a real
// device, and the stock-Filesystem Documents staging -> group-container mover.

