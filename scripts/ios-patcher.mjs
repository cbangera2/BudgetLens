/**
 * Compute every file write the patcher wants; performs no IO itself.
 * @param {ReadFile} readFile
 * @param {ReadTemplate} readTemplate
 * @param {PatcherOptions} options
 * @returns {FileChange[]}
 */
export function planProjectEdits(readFile, readTemplate, options) {
  /** @type {FileChange[]} */
  const changes = []
  const consider = (relativePath, before, after) => {
    if (before !== after) changes.push({ path: relativePath, before, after })
  }

  const entitlementsPath = path.join("App", APP_ENTITLEMENTS)
  const entitlementsBefore = readFile(entitlementsPath)
  consider(
    entitlementsPath,
    entitlementsBefore,
    ensureAppGroupEntitlements(entitlementsBefore, options.appGroup).text,
  )

  const infoPlistPath = path.join("App", "Info.plist")
  const infoBefore = readFile(infoPlistPath)
  if (infoBefore === null) {
    throw new Error(`ios-patcher: missing ${infoPlistPath}; regenerate ios/ via "cap add ios".`)
  }
  consider(
    infoPlistPath,
    infoBefore,
    ensureTopLevelDictKey(
      infoBefore,
      "NSFaceIDUsageDescription",
      "<string>Unlock BudgetLens with Face ID or your device passcode.</string>",
    ).text,
  )

  for (const name of WIDGET_SOURCES) {
    const template = readTemplate(name)
    if (!template.includes(APP_GROUP_TOKEN)) {
      throw new Error(`ios-patcher: template ${name} is missing the ${APP_GROUP_TOKEN} token.`)
    }
    const targetPath = path.join("App", WIDGET_TARGET_NAME, name)
    consider(
      targetPath,
      readFile(targetPath),
      template.replaceAll(APP_GROUP_TOKEN, options.appGroup),
    )
  }

  const widgetPlistPath = path.join("App", WIDGET_TARGET_NAME, WIDGET_INFO_PLIST)
  consider(widgetPlistPath, readFile(widgetPlistPath), buildWidgetExtensionPlist())

  const widgetEntitlementsPath = path.join("App", WIDGET_TARGET_NAME, WIDGET_ENTITLEMENTS)
  const widgetEntitlementsBefore = readFile(widgetEntitlementsPath)
  consider(
    widgetEntitlementsPath,
    widgetEntitlementsBefore,
    ensureAppGroupEntitlements(widgetEntitlementsBefore, options.appGroup).text,
  )

  const pbxprojPath = path.join("App.xcodeproj", "project.pbxproj")
  const pbxprojBefore = readFile(pbxprojPath)
  if (pbxprojBefore === null) {
    throw new Error(`ios-patcher: missing ${pbxprojPath}; regenerate ios/ via "cap add ios".`)
  }
  consider(
    pbxprojPath,
    pbxprojBefore,
    applyPbxprojEdits(pbxprojBefore, { appId: options.appId }).text,
  )

  return changes
}

/**
 * @param {string} capacitorConfigPath
 * @returns {string}
 */
function readAppId(capacitorConfigPath) {
  try {
    const text = readFileSync(capacitorConfigPath, "utf8")
    const match = /appId:\s*"([^"]+)"/.exec(text)
    if (match && match[1]) return match[1]
  } catch {
    // Fall through to the default below.
  }
  return DEFAULT_APP_ID
}

/**
 * @param {string[]} argv
 */
function parseArgs(argv) {
  let projectDir = path.join(REPO_ROOT, "ios")
  let appGroup = DEFAULT_APP_GROUP
  let appId = null
  let dryRun = false
  let check = false
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i]
    if (arg === "--project") {
      const value = argv[i + 1]
      if (!value) throw new Error("ios-patcher: --project needs a directory value.")
      projectDir = path.resolve(value)
      i += 1
    } else if (arg === "--app-group") {
      const value = argv[i + 1]
      if (!value) throw new Error("ios-patcher: --app-group needs a group id value.")
      appGroup = value
      i += 1
    } else if (arg === "--app-id") {
      const value = argv[i + 1]
      if (!value) throw new Error("ios-patcher: --app-id needs a bundle id value.")
      appId = value
      i += 1
    } else if (arg === "--dry-run") {
      dryRun = true
    } else if (arg === "--check") {
      check = true
    } else if (arg === "--help" || arg === "-h") {
      printHelp()
      process.exit(0)
    } else {
      throw new Error(`ios-patcher: unknown argument "${arg}". See --help.`)
    }
  }
  return { projectDir, appGroup, appId, dryRun, check }
}

